/**
 * Data contoh: venue Bandung, harga rupiah wajar, nama Indonesia.
 * Semua tanggal relatif terhadap hari ini supaya app tidak pernah tampil
 * dengan jadwal kedaluwarsa.
 */
export function today(): Date {
  const d = new Date()
  d.setHours(0, 0, 0, 0)
  return d
}

function atHour(dayOffset: number, hour: number): string {
  const d = today()
  d.setDate(d.getDate() + dayOffset)
  d.setHours(hour, 0, 0, 0)
  return d.toISOString()
}

function minutesAgo(m: number): string {
  return new Date(Date.now() - m * 60_000).toISOString()
}

function hoursAgo(h: number): string {
  return new Date(Date.now() - h * 3_600_000).toISOString()
}

interface CourtOpts {
  indoor: boolean
  surface: string
  from?: number
  /** Lapangan bernomor >= ini dihargai `premium` per jam. */
  premiumFrom?: number
  premium?: number
}

function courts(venueId: string, sport: Court['sport'], count: number, opts: CourtOpts): Court[] {
  const start = opts.from ?? 1
  return Array.from({ length: count }, (_, i) => {
    const n = start + i
    const isPremium = opts.premiumFrom !== undefined && n >= opts.premiumFrom
    return {
      id: `${venueId}-c${n}`,
      venueId,
      name: `Lap. ${n}`,
      sport,
      indoor: opts.indoor,
      surface: opts.surface,
      ...(isPremium && opts.premium !== undefined ? { pricePerHourIdr: opts.premium } : {}),
    }
  })
}

